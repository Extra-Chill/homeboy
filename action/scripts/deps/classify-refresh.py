#!/usr/bin/env python3
"""Fail-closed routing for `homeboy deps stack refresh` JSON."""
import json
import sys
from pathlib import Path


def payload(report):
    if "data" in report:
        if report.get("success") is not True:
            raise ValueError("Homeboy refresh command failed")
        return report["data"]
    return report


def classify(report, config):
    report = payload(report)
    edges = report["edges"]
    if not isinstance(edges, list):
        raise ValueError("refresh edges must be an array")
    for edge in edges:
        if edge.get("state") not in ("updated", "current"):
            raise ValueError(f"Dependency could not be resolved/refreshed: {edge}")
        if "breaking" not in edge or edge["breaking"] not in (True, False, None):
            raise ValueError("missing/invalid breaking verdict")
    behind = [e for e in edges if e["state"] == "updated"]
    if not behind:
        return "none"
    if report.get("breaking") is not False or any(e["breaking"] is not False for e in behind):
        return "pr"
    return "release" if config.get("release", {}).get("refresh_dependencies") is True else "pr"


def body(report):
    report = payload(report)
    lines = ["## Dependency refresh", "", "Generated by Homeboy. Review the version changes and gate results before merging.", ""]
    for edge in report["edges"]:
        name = edge.get("package", edge.get("upstream", "dependency"))
        lines.append(f"- **{name}**: `{edge.get('from')}` → `{edge.get('to')}` ({edge['state']}; breaking: {edge.get('breaking')})")
        lines.extend(f"  - {reason}" for reason in edge.get("breaking_reasons", []))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    report = json.loads(Path(sys.argv[1]).read_text())
    config = json.loads(Path(sys.argv[2]).read_text())
    route = classify(report, config)
    Path(sys.argv[3]).write_text(body(report))
    print(f"route={route}")
